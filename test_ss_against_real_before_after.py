from sentence_splitter import split_text_into_sections


def safe_split(text):
    """Never crash, always return a list"""
    try:
        out = split_text_into_sections(text)
        # ensure list of non-empty strings
        if isinstance(out, list) and out:
            return [s.strip() for s in out if s.strip()]
        return [text]
    except Exception as e:
        # log the error but don't kill the test
        return [f"ERROR: {type(e).__name__}: {e}"]

def similarity(a, b):
    if not a and not b:
        return 1.0
    matches = sum(1 for x, y in zip(a, b) if x == y)
    return matches / max(len(a), len(b))

def test_map(name, mapping):
    print(f"\n=== {name} ({len(mapping)} tests) ===")
    passed = 0
    for i, (key, expected) in enumerate(mapping.items(), 1):
        actual = safe_split(key)
        score = similarity(actual, expected)
        ok = score >= 0.9

        trunc = (key[:57] + '...') if len(key) > 60 else key
        print(f"test #{i}) {trunc} :: {'TRUE' if ok else 'FALSE'}")
        print(f"- actual: {actual}")
        print(f"- expected: {expected}")
        if not ok:
            print(f" → {score:.0%}")

        passed += ok
    print(f"{name} → {passed}/{len(mapping)} passed")
    return passed

